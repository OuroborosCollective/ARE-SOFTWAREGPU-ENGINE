"""Issue #286 offline cost calibration contracts.

Synthetic receipts here test validation/replay, NOT real CPU measurements.
Full SHA-pinned 15-pair CPU evidence is generated by GitHub CI separately.
"""
import copy
import hashlib
import json
from pathlib import Path
import tempfile
import unittest

from software_gpu.benchmarks.calibrate_surface_costs import (
    CostEvidenceError, MODE_FLAGS, calibrate, validate_benchmark, validate_model,
    select_replay_policy,
)


SHA = 'a' * 40


def _digest(data):
    return hashlib.sha256(data).hexdigest()


def _fixture_root(folder):
    root = Path(folder)
    paths = {}
    for i in range(10):
        file = root / 'source' / (f'source-{i}.py')
        file.parent.mkdir(exist_ok=True)
        file.write_text(f'fixture {i}\n', encoding='utf8')
        paths[file.relative_to(root).as_posix()] = _digest(file.read_bytes())
    return paths


def _receipt(paths, scenes, *, mode_factor=0.4):
    result = []
    for name, ntriangles, bbox in scenes:
        samples = {}
        plans = {}
        for label, flags in MODE_FLAGS.items():
            value = (8.0 if label == 'abl-noscan-batch' else
                     19.0 if label == 'abl-scan-batch' else
                     22.0 if label == 'abl-scan-scalar' else 20.0)
            samples[label] = [value + (i % 3) * .001 for i in range(15)]
            plans[label] = {
                'scan_min_samples': 64 if flags['scan'] else 9223372036854775807,
                'batch_min_samples': 8 if flags['batch'] else 9223372036854775807,
                'draw_min_bbox_samples_per_triangle': 0,
                'decision': 'planned',
                'counts': {'batch_fragment_calls': 2 if flags['batch'] else 0,
                           'batch_fragment_samples': 4 if flags['batch'] else 0,
                           'corner_edge_evaluations': 7 if flags['scan'] else 0},
                'estimated_bbox_samples': bbox,
                'triangle_count': ntriangles,
                'binned_pairs': ntriangles,
            }
        result.append({'scene': name, 'scene_spec': {'kind': 'fixture', 'triangles': ntriangles,
                                                   'size': .4},
                       'triangles': ntriangles, 'pixels': 64, 'workers': 1,
                       'repeats': 15, 'byte_identical': True,
                       'image_sha256': _digest(name.encode()),
                       'color_sha256': _digest(('rgba' + name).encode()),
                       'depth_sha256': _digest(('depth' + name).encode()),
                       'samples_ms': samples, 'plans': plans})
    return {'protocol': 'are.surface-plan-benchmark.v1', 'activation': 'EXPLICIT_OPT_IN_ONLY',
            'source_paths_sha256': paths, 'python': '3.12', 'os': 'linux',
            'numpy': '2.0', 'environment': {'cpu_model': 'test-only', 'affinity_cpus': 2,
                                         'numpy_build': 'test-only', 'thread_env': {}},
            'results': result}


class TestOfflineCostCalibration(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.sources = _fixture_root(self.root)
        self.train = _receipt(self.sources, [('train-large', 6, 6000),
                                             ('train-middle', 80, 12000)])
        self.holdout = _receipt(self.sources, [('holdout-large', 8, 8000),
                                               ('holdout-middle', 120, 18000)])

    def test_model_is_reproducible_and_bound_to_relevant_source_hashes(self):
        one = calibrate(self.train, self.holdout, self.root, SHA)
        two = calibrate(self.train, self.holdout, self.root, SHA)
        self.assertEqual(one, two)
        self.assertEqual(one['protocol'], 'are.surface-cost-calibration.v1')
        self.assertTrue(one['validated_routes'])
        self.assertTrue(one['default_unchanged'])
        self.assertEqual(one['source_revision'], SHA)
        self.assertIn('affinity_cpus', one['environment'])
        self.assertEqual(validate_model(one), one)
        self.assertEqual(one['model_sha256'], _digest(json.dumps(
            {k: v for k, v in one.items() if k != 'model_sha256'},
            sort_keys=True, separators=(',', ':'), allow_nan=False).encode()))

    def test_invalid_parity_and_unpaired_samples_fail_closed(self):
        for mutation in ('parity', 'sample-count', 'invalid-time', 'worker', 'hash', 'plan'):
            with self.subTest(mutation=mutation):
                bad = copy.deepcopy(self.train)
                row = bad['results'][0]
                if mutation == 'parity':
                    row['byte_identical'] = False
                elif mutation == 'sample-count':
                    row['samples_ms']['abl-scan-batch'].pop()
                elif mutation == 'invalid-time':
                    row['samples_ms']['abl-noscan-batch'][0] = float('nan')
                elif mutation == 'worker':
                    row['workers'] = 0
                elif mutation == 'hash':
                    bad['source_paths_sha256']['source/source-0.py'] = '0' * 64
                elif mutation == 'plan':
                    row['plans']['abl-scan-scalar']['draw_min_bbox_samples_per_triangle'] = 64
                with self.assertRaises(CostEvidenceError):
                    calibrate(bad, self.holdout, self.root, SHA)

    def test_different_environment_or_same_scene_is_not_holdout(self):
        bad = copy.deepcopy(self.holdout)
        bad['environment']['affinity_cpus'] = 1
        with self.assertRaises(CostEvidenceError):
            calibrate(self.train, bad, self.root, SHA)
        bad = copy.deepcopy(self.holdout)
        bad['results'][0]['scene'] = self.train['results'][0]['scene']
        with self.assertRaises(CostEvidenceError):
            calibrate(self.train, bad, self.root, SHA)

    def test_replay_requires_matching_revision_and_validated_bucket(self):
        model = calibrate(self.train, self.holdout, self.root, SHA)
        from software_gpu.graphics.batch_shader import VertexColorShader
        policy = select_replay_policy(model, triangles=8, bbox_samples=8000,
                                      shader=VertexColorShader(), expected_source_revision=SHA)
        self.assertIsNotNone(policy)
        self.assertEqual(policy.scan_min_samples, 9223372036854775807)
        self.assertEqual(policy.batch_min_samples, 8)
        self.assertEqual(policy.selection, 'fixed')
        self.assertIsNone(select_replay_policy(model, triangles=1000, bbox_samples=8000,
                                              shader=VertexColorShader(), expected_source_revision=SHA))
        with self.assertRaises(CostEvidenceError):
            select_replay_policy(model, triangles=8, bbox_samples=8000,
                                 shader=VertexColorShader(), expected_source_revision='b' * 40)
        broken = copy.deepcopy(model)
        broken['validated_routes'].clear()
        with self.assertRaises(CostEvidenceError):
            select_replay_policy(broken, triangles=8, bbox_samples=8000,
                                 shader=VertexColorShader(), expected_source_revision=SHA)

    def test_real_near_plane_clipping_may_split_a_source_face(self):
        # Pre-draw policy operates on prepared triangles, not original faces.
        # Clipping legitimately changes that count before any raster work.
        self.train['results'][0]['triangles'] = 3
        self.holdout['results'][0]['triangles'] = 5
        model = calibrate(self.train, self.holdout, self.root, SHA)
        self.assertIn('tiny:large', model['validated_routes'])

    def test_failed_holdout_keeps_every_bucket_disabled(self):
        bad = copy.deepcopy(self.holdout)
        for case in bad['results']:
            case['samples_ms']['abl-noscan-batch'] = [30.0] * 15
        model = calibrate(self.train, bad, self.root, SHA)
        self.assertFalse(model['validated_routes'])


if __name__ == '__main__':
    unittest.main()
